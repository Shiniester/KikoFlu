"""Regenerate test-only Dart graphs from the same Python prototype functions."""

from pathlib import Path
import base64
import json
from graphs import scene_graph, scene_dynamic_graph, mono_graph
from basic import EQ_FREQUENCIES, equalizer_graph
from composite import full_combination
from modes import mode_chain
from limiter import LIMITER_GRAPH, HOT_GRAPH, limited_prefix, limited_combination

root = Path(__file__).resolve().parents[2]
graphs = {}
for scene in ("bathroom", "through_wall", "telephone"):
    for amount in (0, 50, 100):
        graphs[f"scene_{scene}_{amount}"] = scene_graph(scene, amount)
    graphs[f"dynamic_{scene}"] = scene_dynamic_graph(scene, diagnostic=True)
for rate in (44100, 48000, 96000):
    graphs["mono" + str(rate)] = mono_graph(rate)
for band, frequency in enumerate(EQ_FREQUENCIES):
    for gain in (-15, 15):
        gains = [0] * 10
        gains[band] = gain
        graphs[f"eq{frequency}_{gain}"] = equalizer_graph(gains)
graphs["eq_neutral"] = equalizer_graph([0] * 10)
graphs["full_combination_af"] = full_combination()
graphs["scene_modes_af"] = mode_chain()
graphs["limiter"] = LIMITER_GRAPH
graphs["limiter_hot"] = HOT_GRAPH
graphs["limited_prefix_af"] = limited_prefix()
graphs["limited_combination_af"] = limited_combination()
graphs["boundary_scene"] = scene_dynamic_graph("bathroom").replace(
    "volume@scene_amount=0:", "volume@scene_amount=1:")
target = root / "integration_test/audio_effects_native_graphs.dart"
text = "// Generated by tool/audio_effects/generate_dart.py.\n"
text += "// Test-only prototypes; production must not import this file.\n"
text += "const audioEffectsNativeGraphs = <String, String>{\n"
for name, graph in graphs.items():
    text += "  '" + name + "':\n      r'''" + graph + "''',\n"
text += "};\n"
target.write_text(text, encoding="utf-8")

hls = root / "tool/audio_effects/fixtures/hls"
metadata = json.loads((hls / "fixture.json").read_text(encoding="utf-8"))
text = "// Generated by tool/audio_effects/generate_dart.py.\n"
text += f"const audioEffectsHlsDecodedFrames = {metadata['decoded_frames']};\n"
text += "const audioEffectsHlsFiles = <String, String>{\n"
for path in sorted(hls.iterdir()):
    if path.suffix in (".ts", ".m3u8"):
        text += f"  '/hls/{path.name}': '{base64.b64encode(path.read_bytes()).decode()}',\n"
text += "};\n"
(root / "integration_test/audio_effects_native_hls.dart").write_text(text, encoding="utf-8")
