"""Generate an owned FLAC with a real empty SEEKTABLE for native seek checks."""
import argparse
import base64
import math
import gzip
from pathlib import Path
import struct
import subprocess
import tempfile
import wave

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--ffmpeg', required=True, type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
temporary_root = root/'build/audio-backend-contract'
temporary_root.mkdir(parents=True, exist_ok=True)
with tempfile.TemporaryDirectory(dir=temporary_root) as temp:
    source, encoded = Path(temp)/'source.wav', Path(temp)/'source.flac'
    with wave.open(str(source), 'wb') as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(16000)
        output.writeframes(b''.join(struct.pack('<h', round(.2*math.sin(2*math.pi*500*n/16000)*32767))
                                   for n in range(24*16000)))
    subprocess.run([str(args.ffmpeg.resolve()), '-v', 'error', '-y', '-i', str(source),
                    '-c:a', 'flac', '-compression_level', '12', '-map_metadata', '-1', str(encoded)], check=True)
    data = bytearray(encoded.read_bytes())
    offset = 4
    while not data[offset] & 128:
        offset += 4 + int.from_bytes(data[offset+1:offset+4], 'big')
    length = int.from_bytes(data[offset+1:offset+4], 'big')
    data[offset] &= 127
    end = offset+4+length
    data[end:end] = bytes((128|3,0,0,0))
    # A last metadata block of type 3 and length 0 precedes the original audio frames.
    target = root/'integration_test/audio_backend_native_fixture.dart'
    target.write_text('// Generated by tool/audio_backend_contract/generate_fixture.py.\n'
                      '// Owned 24-second 16 kHz mono signal, with a zero-length type-3 SEEKTABLE.\n'
                      "const audioBackendFlacGzipBase64 = '"+base64.b64encode(gzip.compress(data, mtime=0)).decode()+"';\n"
                      "const audioBackendWavGzipBase64 = '"+base64.b64encode(gzip.compress(source.read_bytes(), mtime=0)).decode()+"';\n", encoding='utf-8')
